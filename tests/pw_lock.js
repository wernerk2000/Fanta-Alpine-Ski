const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const fs = require('fs');
const page0 = fs.readFileSync('/home/claude/fantaski/fanta-ski.html', 'utf8');
const doc = '<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1"><style>body{margin:0}[hidden]{display:none!important}</style></head><body>' + page0 + '</body></html>';
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, timezoneId: 'Europe/Rome', locale: 'it-IT' });
  await ctx.route(/^https?:\/\/(?!local\.test)/, r => r.abort());
  await ctx.route('http://local.test/', r => r.fulfill({ contentType: 'text/html', body: doc }));
  const page = await ctx.newPage(); const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => { window.claude = { use: async n => n === 'artifact' ? { publish: async h => { window.__pub = h; } } : { canEdit: async () => true, isOwner: async () => true, id: async () => 'u1' } }; });
  await page.goto('http://local.test/', { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#tab-gestione');
  await page.click('#tab-regole');
  const rules = await page.textContent('#main');
  console.log(/si chiude un'ora prima della partenza della gara \(ora italiana\)/.test(rules) ? 'ok   rules explain the new deadline' : 'FAIL rules');
  await page.click('#tab-gare');
  await page.click('[data-act="race"][data-v="m06"]');
  const det = await page.textContent('.rdet');
  console.log(/Partenza 19:00 ora italiana · formazioni entro gio 3 dic, 18:00/.test(det) ? 'ok   Beaver Creek: start 19:00, lineups until 18:00' : 'FAIL detail ' + det.slice(0, 120));
  await page.click('[data-act="race"][data-v="m06"]');
  await page.click('[data-act="race"][data-v="m02"]');
  console.log(/Partenza 10:15 ora italiana · formazioni entro dom 15 nov, 09:15/.test(await page.textContent('.rdet')) ? 'ok   Levi: start 10:15, lineups until 09:15' : 'FAIL levi ' + (await page.textContent('.rdet')).slice(0, 120));
  await page.click('#tab-gestione');
  await page.click('[data-act="adm"][data-v="gare"]');
  await page.selectOption('#esel', 'm02');
  await page.fill('#eh', '09:15');
  await page.click('[data-act="rsave"]');
  await page.click('#tab-gare');
  if (!(await page.$('.rdet'))) await page.click('[data-act="race"][data-v="m02"]');
  console.log(/Partenza 09:15 ora italiana · formazioni entro dom 15 nov, 08:15/.test(await page.textContent('.rdet')) ? 'ok   start time edited in Gestione moves the deadline' : 'FAIL edit ' + (await page.textContent('.rdet')).slice(0, 120));
  const hdr = await page.textContent('.nextg');
  console.log(/formazione entro sab 24 ott, 09:00/.test(hdr) ? 'ok   header: next deadline Sölden 09:00' : 'FAIL header ' + hdr);
  console.log(errors.length ? 'FAIL ' + errors : 'ok   no errors');
  await browser.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
